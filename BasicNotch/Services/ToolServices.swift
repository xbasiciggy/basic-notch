// MARK: - Clipboard history

/// Remembers the last 30 bits of text you copied (in memory only; cleared when the app quits).
/// Skips anything password managers mark as concealed or transient.
@MainActor
final class ClipboardService: ObservableObject {
    struct Item: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
    }

    @Published private(set) var items: [Item] = []
    @Published var paused = false

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                  "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !paused else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes),
              let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty else { return }
        let clipped = String(text.prefix(5000))
        items.removeAll { $0.text == clipped }
        items.insert(Item(text: clipped, date: Date()), at: 0)
        if items.count > 30 { items.removeLast(items.count - 30) }
    }

    func copy(_ item: Item) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(item.text, forType: .string)
    }

    func remove(_ item: Item) { items.removeAll { $0 == item } }
    func clear() { items.removeAll() }
}

// MARK: - Focus timer

@MainActor
final class FocusTimer: ObservableObject {
    @Published private(set) var duration: TimeInterval = 25 * 60
    @Published private(set) var remaining: TimeInterval = 25 * 60
    @Published private(set) var isRunning = false
    var onFinish: () -> Void = {}

    private var endDate: Date?
    private var timer: Timer?

    var progress: Double { duration > 0 ? 1 - remaining / duration : 0 }
    var isActive: Bool { isRunning || remaining < duration }

    var label: String {
        let s = Int(remaining.rounded(.up))
        return s >= 3600 ? String(format: "%d:%02d:%02d", s / 3600, s / 60 % 60, s % 60) : String(format: "%d:%02d", s / 60, s % 60)
    }

    func set(minutes: Int) {
        stopTimer()
        duration = TimeInterval(minutes * 60)
        remaining = duration
        isRunning = false
    }

    func start() {
        guard !isRunning, remaining > 0 else { return }
        endDate = Date().addingTimeInterval(remaining)
        isRunning = true
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func pause() {
        guard isRunning else { return }
        tick()
        stopTimer()
        isRunning = false
    }

    func reset() {
        stopTimer()
        isRunning = false
        remaining = duration
    }

    private func tick() {
        guard let end = endDate else { return }
        let left = max(0, end.timeIntervalSinceNow)
        if Int(left.rounded(.up)) != Int(remaining.rounded(.up)) || left == 0 { remaining = left }
        if left <= 0 {
            stopTimer()
            isRunning = false
            remaining = duration
            NSSound(named: "Glass")?.play()
            onFinish()
        }
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
        endDate = nil
    }
}

// MARK: - System stats

struct ProcessMemory: Identifiable {
    var id: String { key }
    let key: String
    let name: String
    var bytes: UInt64
    var processCount: Int
    let appPath: String?
}

@MainActor
final class SystemStatsService: ObservableObject {
    @Published private(set) var cpu: Double = 0  // 0…1
    @Published private(set) var cpuHistory: [Double] = []
    @Published private(set) var memoryUsed: UInt64 = 0
    @Published private(set) var memoryTotal: UInt64 = ProcessInfo.processInfo.physicalMemory
    @Published private(set) var downRate: Double = 0  // bytes/s
    @Published private(set) var upRate: Double = 0
    @Published private(set) var downHistory: [Double] = []
    /// Biggest memory users, grouped by app. Only sampled while someone is looking (hovering the Memory card).
    @Published private(set) var topMemory: [ProcessMemory] = []
    private var memoryLoop: Task<Void, Never>?

    func watchTopMemory(_ on: Bool) {
        memoryLoop?.cancel()
        memoryLoop = nil
        guard on else { return }
        memoryLoop = Task { [weak self] in
            while !Task.isCancelled {
                let top = await Task.detached(priority: .utility) { Self.sampleTopMemory(limit: 8) }.value
                guard !Task.isCancelled else { return }
                self?.topMemory = top
                try? await Task.sleep(for: .seconds(3))
            }
        }
    }

    /// Per-process memory footprint (what Activity Monitor calls "Memory"), with helpers rolled up into their app.
    private nonisolated static func sampleTopMemory(limit: Int) -> [ProcessMemory] {
        let estimate = proc_listallpids(nil, 0)
        guard estimate > 0 else { return [] }
        var pids = [pid_t](repeating: 0, count: Int(estimate) + 64)
        let count = proc_listallpids(&pids, Int32(pids.count * MemoryLayout<pid_t>.size))
        guard count > 0 else { return [] }

        var groups: [String: ProcessMemory] = [:]
        var pathBuffer = [CChar](repeating: 0, count: 4096)
        var nameBuffer = [CChar](repeating: 0, count: 256)
        for pid in pids.prefix(Int(count)) where pid > 0 {
            var info = rusage_info_v4()
            let ok = withUnsafeMutablePointer(to: &info) { ptr in
                ptr.withMemoryRebound(to: rusage_info_t?.self, capacity: 1) { proc_pid_rusage(pid, RUSAGE_INFO_V4, $0) }
            }
            guard ok == 0, info.ri_phys_footprint > 0 else { continue }  // other users' / system processes aren't readable

            let path = proc_pidpath(pid, &pathBuffer, UInt32(pathBuffer.count)) > 0 ? String(cString: pathBuffer) : ""
            let key: String, name: String, appPath: String?
            if let range = path.range(of: ".app/") {
                // Roll helpers (e.g. "Google Chrome Helper (Renderer)") up into the outermost app bundle.
                let bundle = String(path[..<range.lowerBound]) + ".app"
                key = bundle
                appPath = bundle
                name = (bundle as NSString).lastPathComponent.replacingOccurrences(of: ".app", with: "")
            } else {
                let short = proc_name(pid, &nameBuffer, UInt32(nameBuffer.count)) > 0 ? String(cString: nameBuffer) : ""
                name = short.isEmpty ? (path as NSString).lastPathComponent : short
                key = name
                appPath = nil
            }
            guard !name.isEmpty else { continue }
            if var existing = groups[key] {
                existing.bytes += info.ri_phys_footprint
                existing.processCount += 1
                groups[key] = existing
            } else {
                groups[key] = ProcessMemory(key: key, name: name, bytes: info.ri_phys_footprint, processCount: 1, appPath: appPath)
            }
        }
        return Array(groups.values.sorted { $0.bytes > $1.bytes }.prefix(limit))
    }

    private var lastCPU: (busy: UInt64, total: UInt64)?
    private var lastNet: (down: UInt64, up: UInt64, date: Date)?
    private var loop: Task<Void, Never>?

    func start() {
        loop = Task { [weak self] in
            while !Task.isCancelled {
                self?.sample()
                try? await Task.sleep(for: .seconds(2))
            }
        }
    }

    private func sample() {
        if let ticks = Self.cpuTicks() {
            if let last = lastCPU, ticks.total > last.total {
                cpu = Double(ticks.busy - last.busy) / Double(ticks.total - last.total)
                cpuHistory = Array((cpuHistory + [cpu]).suffix(60))
            }
            lastCPU = ticks
        }
        memoryUsed = Self.memoryUsed()
        let net = Self.networkBytes()
        let now = Date()
        if let last = lastNet {
            let dt = max(now.timeIntervalSince(last.date), 0.1)
            downRate = Double(net.down &- last.down) / dt
            upRate = Double(net.up &- last.up) / dt
            if downRate < 0 || downRate > 1e11 { downRate = 0 }
            if upRate < 0 || upRate > 1e11 { upRate = 0 }
            downHistory = Array((downHistory + [downRate]).suffix(60))
        }
        lastNet = (net.down, net.up, now)
    }

    private static func cpuTicks() -> (busy: UInt64, total: UInt64)? {
        var info: processor_info_array_t?
        var cpuCount: mach_msg_type_number_t = 0
        var infoCount: mach_msg_type_number_t = 0
        guard host_processor_info(mach_host_self(), PROCESSOR_CPU_LOAD_INFO, &cpuCount, &info, &infoCount) == KERN_SUCCESS,
              let info else { return nil }
        defer {
            vm_deallocate(mach_task_self_, vm_address_t(bitPattern: info),
                          vm_size_t(infoCount) * vm_size_t(MemoryLayout<integer_t>.stride))
        }
        var busy: UInt64 = 0, total: UInt64 = 0
        for i in 0..<Int(cpuCount) {
            let base = Int(CPU_STATE_MAX) * i
            let user = UInt64(info[base + Int(CPU_STATE_USER)])
            let system = UInt64(info[base + Int(CPU_STATE_SYSTEM)])
            let nice = UInt64(info[base + Int(CPU_STATE_NICE)])
            let idle = UInt64(info[base + Int(CPU_STATE_IDLE)])
            busy += user + system + nice
            total += user + system + nice + idle
        }
        return (busy, total)
    }

    private static func memoryUsed() -> UInt64 {
        var stats = vm_statistics64()
        var count = mach_msg_type_number_t(MemoryLayout<vm_statistics64_data_t>.size / MemoryLayout<integer_t>.size)
        let result = withUnsafeMutablePointer(to: &stats) {
            $0.withMemoryRebound(to: integer_t.self, capacity: Int(count)) {
                host_statistics64(mach_host_self(), HOST_VM_INFO64, $0, &count)
            }
        }
        guard result == KERN_SUCCESS else { return 0 }
        let page = UInt64(vm_kernel_page_size)
        return (UInt64(stats.active_count) + UInt64(stats.wire_count) + UInt64(stats.compressor_page_count)) * page
    }

    private static func networkBytes() -> (down: UInt64, up: UInt64) {
        var addrs: UnsafeMutablePointer<ifaddrs>?
        guard getifaddrs(&addrs) == 0 else { return (0, 0) }
        defer { freeifaddrs(addrs) }
        var down: UInt64 = 0, up: UInt64 = 0
        var cursor = addrs
        while let a = cursor {
            if let addr = a.pointee.ifa_addr, addr.pointee.sa_family == UInt8(AF_LINK),
               let data = a.pointee.ifa_data,
               !String(cString: a.pointee.ifa_name).hasPrefix("lo") {
                let d = data.assumingMemoryBound(to: if_data.self).pointee
                down += UInt64(d.ifi_ibytes)
                up += UInt64(d.ifi_obytes)
            }
            cursor = a.pointee.ifa_next
        }
        return (down, up)
    }

    static func bytes(_ value: Double) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(value), countStyle: .binary)
    }
}

// MARK: - AirPods / Bluetooth battery

@MainActor
final class AirPodsService: ObservableObject {
    struct Device: Identifiable, Equatable {
        var id: String { name }
        let name: String
        let left: Int?
        let right: Int?
        let caseLevel: Int?
        let main: Int?

        var summary: String {
            var parts: [String] = []
            if let left { parts.append("L \(left)%") }
            if let right { parts.append("R \(right)%") }
            if let caseLevel { parts.append("Case \(caseLevel)%") }
            if let main { parts.append("\(main)%") }
            return parts.joined(separator: " · ")
        }

        var lowest: Int? { [left, right, main].compactMap { $0 }.min() }
    }

    /// Connected Bluetooth audio devices that report a battery level.
    @Published private(set) var devices: [Device] = []
    var onConnect: (Device) -> Void = { _ in }

    private var known: Set<String>?
    private var loop: Task<Void, Never>?

    func start() {
        loop = Task { [weak self] in
            while !Task.isCancelled {
                await self?.refresh()
                try? await Task.sleep(for: .seconds(20))
            }
        }
    }

    func refresh() async {
        let found = await Task.detached(priority: .utility) { Self.readDevices() }.value
        let names = Set(found.map(\.name))
        if let known {
            for device in found where !known.contains(device.name) { onConnect(device) }
        }
        known = names
        devices = found
    }

    private nonisolated static func readDevices() -> [Device] {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/sbin/system_profiler")
        process.arguments = ["SPBluetoothDataType", "-json"]
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = FileHandle.nullDevice
        guard (try? process.run()) != nil else { return [] }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()

        guard let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let controllers = root["SPBluetoothDataType"] as? [[String: Any]] else { return [] }
        func level(_ info: [String: Any], _ key: String) -> Int? {
            (info[key] as? String).flatMap { Int($0.replacingOccurrences(of: "%", with: "")) }
        }
        var result: [Device] = []
        for controller in controllers {
            for entry in controller["device_connected"] as? [[String: Any]] ?? [] {
                for (name, value) in entry {
                    guard let info = value as? [String: Any] else { continue }
                    let device = Device(name: name,
                                        left: level(info, "device_batteryLevelLeft"),
                                        right: level(info, "device_batteryLevelRight"),
                                        caseLevel: level(info, "device_batteryLevelCase"),
                                        main: level(info, "device_batteryLevelMain"))
                    let isAudio = (info["device_minorType"] as? String) == "Headphones" || device.left != nil
                    if isAudio && device.lowest != nil { result.append(device) }
                }
            }
        }
        return result
    }
}
